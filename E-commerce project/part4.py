    knn_acc, knn_prec, knn_rec, knn_f1, _ = calc_metrics(knn_tp, knn_fp, knn_tn, knn_fn)

    # Task 2.8 (Money optimization)
    train_probs = sigmoid(X_train_std @ weights + bias)
