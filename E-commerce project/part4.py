    d45 = wcss_k4 - wcss_k5
    d56 = wcss_k5 - wcss_k6

    elbow_k = 3
    for K in [3, 4, 5]:
        drop_curr = wcss_results[K] - wcss_results[K+1]
        drop_prev = wcss_results[K-1] - wcss_results[K]
