    wcss_k3 = wcss_results[3]
    wcss_k4 = wcss_results[4]
    wcss_k5 = wcss_results[5]
    wcss_k6 = wcss_results[6]

    # Task 3.2: Elbow choice
    d23 = wcss_k2 - wcss_k3
